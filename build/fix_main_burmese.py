with open("data/book1-units.json", encoding="utf-8") as f:
    units = json.load(f)

for u in units:
    n = u["n"]
    mm_list = BURMESE.get(n)
    if not mm_list:
        continue
    lines = u["main"]["lines"]
    if len(mm_list) != len(lines):
        print(f"WARNING unit {n}: {len(mm_list)} burmese vs {len(lines)} lines")
        continue
    for line, mm in zip(lines, mm_list):
        line[1] = mm  # replace the erroneous slot with real Burmese

with open("data/book1-units.json", "w", encoding="utf-8") as f:
    json.dump(units, f, ensure_ascii=False, indent=1)

print("patched", len(units), "units")
